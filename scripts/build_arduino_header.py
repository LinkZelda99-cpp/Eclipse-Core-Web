#!/usr/bin/env python3
"""Bundle CORE WEB's source assets into the header served by the UNO R4 WiFi."""
from pathlib import Path
import argparse

parser = argparse.ArgumentParser()
parser.add_argument("output", type=Path, help="Path to CoreWebPage.h in the firmware repository")
args = parser.parse_args()

root = Path(__file__).resolve().parents[1]
html = (root / "index.html").read_text(encoding="utf-8")
css = (root / "assets" / "app.css").read_text(encoding="utf-8")
js = (root / "assets" / "app.js").read_text(encoding="utf-8")
html = html.replace('<link rel="stylesheet" href="assets/app.css">', f"<style>\n{css}\n</style>")
html = html.replace('<script src="assets/app.js"></script>', f"<script>\n{js}\n</script>")
if "assets/app.css" in html or "assets/app.js" in html:
    raise SystemExit("Could not inline one or more CORE WEB assets.")

delimiter = "COREWEB"
if f"){delimiter}\"" in html:
    raise SystemExit("HTML contains the raw-string delimiter; choose another delimiter.")
args.output.parent.mkdir(parents=True, exist_ok=True)
args.output.write_text(
    "#pragma once\n// Generated by ECLIPSE CORE WEB/scripts/build_arduino_header.py.\n"
    f'const char CORE_WEB_HTML[] = R"{delimiter}({html}){delimiter}";\n',
    encoding="utf-8",
)
print(f"Generated {args.output}")
